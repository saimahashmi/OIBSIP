for a, (xcol, ycol) in zip(ax, pairs):
    sns.scatterplot(data=plot_df, x=xcol, y=ycol, hue='Cluster',
                    palette='tab10', s=15, alpha=0.6, ax=a)
    a.set_title(f'{xcol} vs {ycol} by Cluster')
    a.set_xlabel(f'log(1 + {xcol})')
